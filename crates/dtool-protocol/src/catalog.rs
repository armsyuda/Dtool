    pub fn get(&self, name: &str) -> Option<&CommandSpec> {
        self.specs.iter().find(|spec| spec.name == name)
    }

    pub fn resolve(&self, name: &str) -> Option<&CommandSpec> {
        self.get(name).or_else(|| self.specs.iter().find(|spec| spec.aliases.contains(&name)))
    }

    pub fn all(&self) -> &[CommandSpec] {
        &self.specs
    }

    pub fn names(&self) -> Vec<String> {
        self.specs.iter().map(|spec| spec.name.to_string()).collect()
    }

    pub fn contains(&self, name: &str) -> bool {
        self.get(name).is_some()
    }

    pub fn assert_named(&self, name: &str) -> Result<(), String> {
        if name.is_empty() {
            return Err("UNKNOWN_COMMAND".to_string());
        }
        if self.resolve(name).is_none() {
            return Err("UNKNOWN_COMMAND".to_string());
        }
        Ok(())
    }
